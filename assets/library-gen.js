  function pickN(arr, n) {
    var a = (arr || []).slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a.slice(0, n);
  }

  /* 按文风生成一套信息库（全部条目为 { name, desc }，角色额外含 role） */
  function gen(type) {
    var p = PRESETS[type] || PRESETS['东方玄幻'];
    var heroNames = pickN(p.heroNames, 1);
    var heroDesc = p.heroDesc[Math.floor(Math.random() * p.heroDesc.length)];
    var characters = [{ name: heroNames[0], role: '主角', desc: heroDesc }];
    pickN(p.sideItems, 5).forEach(function (s) {
      characters.push({ name: s.name, role: s.role || '配角', desc: s.desc });
    });
    pickN(p.villainItems, 2).forEach(function (v) {
      characters.push({ name: v.name, role: '反派', desc: v.desc });
    });
    return {
      characters: characters,
      skills: pickN(p.skillItems, 6),
      places: pickN(p.placeItems, 6),
      storylines: pickN(p.storyItems, 4),
      quotes: pickN(p.quoteItems, 8),
      settings: pickN(p.settingItems, 6),
      chapterOutlines: pickN(p.outlineItems, 12)
    };
  }

